std::size_t R5900CompiledBlockModuleBuildResult::accepted_count() const noexcept {
    return static_cast<std::size_t>(std::count_if(
        inventory.begin(), inventory.end(), [](const R5900CompiledBlockModuleInventoryEntry& entry) {
            return entry.disposition == R5900CompiledBlockModuleDisposition::Accepted;
        }));
}

std::size_t R5900CompiledBlockModuleBuildResult::lifter_rejected_count() const noexcept {
    return static_cast<std::size_t>(std::count_if(
        inventory.begin(), inventory.end(), [](const R5900CompiledBlockModuleInventoryEntry& entry) {
            return entry.disposition == R5900CompiledBlockModuleDisposition::LifterRejected;
        }));
}

std::size_t R5900CompiledBlockModuleBuildResult::generation_limit_exceeded_count() const noexcept {
    return static_cast<std::size_t>(std::count_if(
        inventory.begin(), inventory.end(), [](const R5900CompiledBlockModuleInventoryEntry& entry) {
            return entry.disposition == R5900CompiledBlockModuleDisposition::GenerationLimitExceeded;
        }));
}

