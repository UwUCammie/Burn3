enum class R5900ControlFlow : std::uint8_t {
    None,
    Branch,
    Jump,
    Call,
    Return,
    Exception,
};

struct DecodedR5900Instruction {
    GuestAddress pc{};
    std::uint32_t word{};
    R5900InstructionKind kind{R5900InstructionKind::Unknown};
    R5900ControlFlow control_flow{R5900ControlFlow::None};
    std::uint8_t rs{};
    std::uint8_t rt{};
    std::uint8_t rd{};
    std::uint8_t shift{};
    std::uint16_t immediate{};
    GuestAddress target{};
    bool has_delay_slot{};

    [[nodiscard]] std::int32_t signed_immediate() const noexcept;
};

[[nodiscard]] DecodedR5900Instruction decode_r5900(GuestAddress pc, std::uint32_t word) noexcept;
[[nodiscard]] std::string_view mnemonic(R5900InstructionKind kind) noexcept;
[[nodiscard]] std::string format_r5900_instruction(const DecodedR5900Instruction& instruction);

