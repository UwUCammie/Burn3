"""Build the optimized executable using only this release and the user's ISO data."""
import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import uuid
import threading


def tree_digest(root):
    identity = hashlib.sha256()
    for path in sorted(p for p in root.rglob('*') if p.is_file()):
        identity.update(path.relative_to(root).as_posix().encode())
        identity.update(bytes.fromhex(digest(path)))
    return identity.hexdigest()


def unit_key(preprocessed, arguments, compiler_identity):
    identity = hashlib.sha256(json.dumps([1, compiler_identity, arguments], separators=(',', ':')).encode())
    with preprocessed.open('rb') as stream:
        while block := stream.read(1024 * 1024):
            identity.update(block)
    return identity.hexdigest()


class ObjectCache:
    """Local, content-addressed objects. Receipts are published after objects."""
    def __init__(self, root):
        self.root = root
        self.lock = threading.Lock()
        root.mkdir(parents=True, exist_ok=True)

    def restore(self, key, destination):
        with self.lock:
            return self._restore(key, destination)

    def _restore(self, key, destination):
        obj = self.root / (key + '.o')
        receipt = self.root / (key + '.json')
        try:
            saved = json.loads(receipt.read_text())
            if saved['key'] != key or saved['sha256'] != digest(obj):
                return False
            shutil.copy2(obj, destination)
            return True
        except (OSError, ValueError, KeyError, TypeError):
            return False

    def store(self, key, source):
        with self.lock:
            self._store(key, source)

    def _store(self, key, source):
        obj = self.root / (key + '.o')
        pending = obj.with_suffix('.' + uuid.uuid4().hex + '.pending')
        shutil.copy2(source, pending)
        checksum = digest(pending)
        pending.replace(obj)
        receipt = self.root / (key + '.json')
        pending_receipt = receipt.with_suffix('.' + uuid.uuid4().hex + '.tmp')
        pending_receipt.write_text(json.dumps({'key': key, 'sha256': checksum}))
        pending_receipt.replace(receipt)


def compile_unit(command, run, cache, compiler_identity, source, generated, objects):
    """Preprocess actual dependencies before deciding whether compilation is needed.

    Compile that same preprocessed input on a miss, so the key describes exactly
    what the compiler consumed. Unused headers cannot invalidate an object.
    """
    cut = command.index('-c')
    output = Path(command[-1])
    preprocessed = output.with_suffix('.ii')
    roots = [(str(source), '/burn3/source'), (str(generated), '/burn3/generated'),
             (str(objects), '/burn3/objects')]
    maps = ['-ffile-prefix-map=' + original + '=' + canonical for original, canonical in roots]
    # Include directives use forward slashes, including on Windows.
    maps += ['-ffile-prefix-map=' + Path(original).as_posix() + '=' + canonical for original, canonical in roots]
    arguments = [str(x) for x in command[:cut]] + maps
    try:
        run(arguments + ['-E', '-P', command[cut + 1], '-o', preprocessed])
        normalized = []
        kit = source.parent
        replacements = roots + [(str(kit / 'compiler'), '/burn3/compiler')]
        for argument in arguments:
            for original, canonical in sorted(replacements, key=lambda x: -len(x[0])):
                argument = argument.replace(original, canonical).replace(Path(original).as_posix(), canonical)
            normalized.append(argument)
        key = unit_key(preprocessed, normalized, compiler_identity)
        if cache.restore(key, output):
            return 'reused'
        run(arguments + ['-x', 'c++-cpp-output', '-c', preprocessed, '-o', output])
        cache.store(key, output)
        return 'compiled'
    finally:
        preprocessed.unlink(missing_ok=True)


def digest(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


class GeneratedCache:
    """Only the release's exact qualified generated bytes are reusable."""
    def __init__(self, root, expected):
        self.expected = expected
        key = hashlib.sha256(json.dumps(expected, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
        self.root = root / key

    def restore(self, destination):
        try:
            if not self.expected or any(digest(contained(self.root, name)) != checksum
                                        for name, checksum in self.expected.items()):
                return False
            for name in self.expected:
                target = contained(destination, name)
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(contained(self.root, name), target)
            return True
        except (OSError, ValueError):
            return False

    def store(self, source):
        for name, checksum in self.expected.items():
            if digest(contained(source, name)) != checksum:
                raise RuntimeError('Generated native code differs from the qualified optimized build: ' + name)
        self.root.parent.mkdir(parents=True, exist_ok=True)
        stage = self.root.with_name(self.root.name + '.' + uuid.uuid4().hex + '.pending')
        try:
            for name in self.expected:
                target = contained(stage, name)
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(contained(source, name), target)
            if self.root.exists():
                # An invalid prior cache is expendable, never user game data.
                shutil.rmtree(self.root)
            stage.replace(self.root)
        finally:
            if stage.exists():
                shutil.rmtree(stage)


def link_key(command, compiler_identity, inputs):
    """A link is reusable only with identical ordered input bytes and flags."""
    identity = hashlib.sha256(json.dumps([1, compiler_identity, command], separators=(',', ':')).encode())
    for path in inputs:
        identity.update(bytes.fromhex(digest(path)))
    return identity.hexdigest()


def incremental_link_flags(root, compiler_identity):
    """Keep GCC's optimized partitions across releases using this toolchain.

    This is an execution cache, not a change to the link's optimization policy;
    leave both the per-unit and whole-executable cache identities unchanged.
    """
    cache = contained(root / '.launcher/native-lto/v1', compiler_identity)
    cache.mkdir(parents=True, exist_ok=True)
    # The current game has over 130 partitions. MinGW lacks GCC's file-locking
    # support, so too small a limit can prune a partition before ld consumes it.
    return ['-flto-incremental=' + str(cache), '-flto-incremental-cache-size=256']


def link_incrementally(command, run, root, compiler_identity):
    try:
        run([*command, *incremental_link_flags(root, compiler_identity)])
    except (OSError, subprocess.CalledProcessError):
        # The optimization cache is optional. In particular, MinGW cache
        # pruning or an interrupted/corrupted entry must not block an update.
        print('Cached linking failed; retrying the normal optimized link...', flush=True)
        run(command)
        # Do not keep retrying damaged cache entries on every later update.
        # This private cache is disposable, and setup holds the install lock.
        try:
            shutil.rmtree(contained(root / '.launcher/native-lto/v1', compiler_identity))
        except OSError:
            pass


def reconstruct(recipe, elf_path, destination):
    elf = elf_path.read_bytes()
    if hashlib.sha256(elf).hexdigest() != recipe['elf_sha256']:
        raise ValueError('Unsupported game revision')
    for image in recipe['images']:
        if not 0 < image['size'] <= 16384:
            raise ValueError('Invalid microcode image size')
        data = bytearray(image['size'])
        position = 0
        for target, source, count in image['spans']:
            if target != position or count < 1 or target + count > len(data):
                raise ValueError('Invalid reconstruction extent')
            if source != -1:
                if source < 0 or source + count > len(elf):
                    raise ValueError('Reconstruction reads outside the executable')
                data[target:target + count] = elf[source:source + count]
            position += count
        if position != len(data) or hashlib.sha256(data).hexdigest() != image['sha256']:
            raise ValueError('Microcode reconstruction checksum mismatch')
        path = contained(destination, image['path'])
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    for relative, text in recipe['manifests'].items():
        path = contained(destination, relative)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)


def contained(root, relative):
    if '\\' in relative or ':' in relative or any(part in ('', '.', '..') for part in relative.split('/')):
        raise ValueError('Unsafe reconstruction path')
    path = root / relative
    if not path.resolve().is_relative_to(root.resolve()):
        raise ValueError('Reconstruction path escapes destination')
    return path


def setup(release, root, jobs):
    release = release.resolve()
    root = root.resolve()
    kit = release / 'setup'
    manifest = json.loads((kit / 'build.json').read_text())
    elf = root / 'game/SLUS_210.50'
    if digest(elf) != manifest['elf_sha256']:
        raise ValueError('The imported executable does not match this release')
    print('Preparing original menu fonts and artwork from your ISO...', flush=True)
    subprocess.run([sys.executable, str(kit / 'tools/build_native_ui_assets.py'),
                    '--game', str(root / 'game'), '--output', str(root / 'cache/ui')],
                   check=True, creationflags=subprocess.CREATE_NO_WINDOW)
    destination = root / '.launcher/native' / manifest['build_id']
    destination.mkdir(parents=True, exist_ok=True)
    # Windows prevents concurrent setup jobs from compiling into the same cache.
    import msvcrt
    with (destination.parent / 'setup.lock').open('a+b') as lock:
        lock.seek(0)
        try:
            msvcrt.locking(lock.fileno(), msvcrt.LK_NBLCK, 1)
        except OSError:
            raise RuntimeError('Another game setup is already running') from None
        try:
            executable = destination / 'takedown-recomp.exe'
            receipt = destination / 'ready.json'
            if receipt.exists() and executable.exists():
                saved = json.loads(receipt.read_text())
                if saved.get('executable_sha256') == digest(executable):
                    return executable
            inputs = destination / 'inputs'
            generated = destination / 'generated'
            ee = generated / 'ee'; vu0 = generated / 'vu0'; vu1 = generated / 'vu1'
            for folder in (ee, vu0, vu1):
                folder.mkdir(parents=True, exist_ok=True)
                # An interrupted older generator must not leave an extra shard
                # outside the release's qualified inventory for the linker.
                for module in folder.glob('*.inc'):
                    if module.relative_to(generated).as_posix() not in manifest['generated_sha256']:
                        module.unlink()
            shutil.copy2(kit / 'metadata/ee_aot_layout.tsv', ee / 'ee_aot_layout.tsv')
            env = os.environ.copy()
            compiler_bin = kit / 'compiler/bin'
            env['PATH'] = str(compiler_bin) + os.pathsep + str(release / 'bin') + os.pathsep + str(Path(os.environ['WINDIR']) / 'System32')
            env['MAKE'] = '"' + str(compiler_bin / 'mingw32-make.exe') + '"'
            # Never inherit a developer machine's GCC search overrides.
            for key in ('GCC_EXEC_PREFIX', 'COMPILER_PATH', 'LIBRARY_PATH', 'CPATH', 'CPLUS_INCLUDE_PATH', 'C_INCLUDE_PATH'):
                env.pop(key, None)

            def run(arguments):
                result = subprocess.run([str(x) for x in arguments], env=env, cwd=destination,
                                        stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                        text=True, encoding='utf-8', errors='replace',
                                        creationflags=subprocess.CREATE_NO_WINDOW)
                if result.returncode:
                    print(result.stdout[:20000], flush=True)
                    result.check_returncode()

            generated_cache = GeneratedCache(root / '.launcher/native-generated/v1', manifest['generated_sha256'])
            if generated_cache.restore(generated):
                print('Reused verified EE, VU0 and VU1 native code from the previous setup.', flush=True)
            else:
                print('Reconstructing native-code inputs from your ISO...', flush=True)
                reconstruct(json.loads((kit / 'recipe.json').read_text()), elf, inputs)
                print('Generating EE, VU0 and VU1 native code...', flush=True)
                run([kit / 'tools/takedown-ee-aot.exe', '--elf', elf, '--functions', kit / 'metadata/functions.csv',
                     '--profile', kit / 'metadata/profile.tsv', '--misses', kit / 'metadata/misses.tsv',
                     '--coverage', '0.99', '--all', '--discover', '--ui-session-stops', '--output', ee / 'ee_aot_module.inc'])
                run([sys.executable, kit / 'tools/vu0_aot_generator.py', inputs / 'vu0-aot/inputs', vu0 / 'vu0_aot_module.inc'])
                vu_arguments = [kit / 'tools/takedown-vu1-aot.exe']
                for group in ('inputs', 'census-race', 'census-time-attack', 'census-crash'):
                    vu_arguments += ['--inputs', inputs / 'vu1-aot' / group]
                run(vu_arguments + ['--flushed-clamps', '--cross-edge-operand-proofs',
                                    '--output', vu1 / 'vu1_aot_module_flushed.inc'])
                generated_cache.store(generated)
            for relative, expected in manifest['generated_sha256'].items():
                if digest(generated / relative) != expected:
                    raise RuntimeError('Generated native code differs from the qualified optimized build: ' + relative)
            print('Native code verified. Checking what needs rebuilding...', flush=True)
            objects = destination / 'objects'; objects.mkdir(exist_ok=True)
            gxx = compiler_bin / 'g++.exe'
            source = kit / 'source'
            sysroot = '--sysroot=' + str(kit / 'compiler')
            common = [gxx, sysroot, '-std=gnu++20', '-DNDEBUG', '-I' + str(source / 'include'), '-I' + str(source / 'generated')]
            commands = []
            for name, macro, module in (
                    ('ee_aot', 'TAKEDOWN_LOCAL_EE_AOT_MODULE', ee / 'ee_aot_module.inc'),
                    ('vu0_micro_interpreter', 'TAKEDOWN_LOCAL_VU0_AOT_MODULE', vu0 / 'vu0_aot_module.inc'),
                    ('vu1_micro_interpreter', 'TAKEDOWN_LOCAL_VU1_AOT_MODULE', vu1 / 'vu1_aot_module_flushed.inc')):
                flags = ['-O3', '-flto=auto', '-fno-fat-lto-objects']
                if name.startswith('vu1'):
                    flags += ['-ffp-contract=off', '-frounding-math']
                commands.append(common + flags + ['-D' + macro + '="' + module.as_posix() + '"', '-c', source / 'src/guest' / (name + '.cpp'), '-o', objects / (name + '.o')])
            for shard in sorted(ee.glob('ee_aot_shard_*.inc')):
                wrapper = objects / (shard.stem + '.cpp')
                wrapper.write_text('#include "' + (source / 'src/guest/ee_aot_abi.hpp').as_posix() + '"\nnamespace takedown::guest::ee_aot_detail {\n#include "' + shard.as_posix() + '"\n}\n')
                flags = ['-O1', '-fno-lto']
                if '_cold_' in shard.stem:
                    flags += ['-DTAKEDOWN_EE_AOT_COLD_SHARD']
                commands.append(common + flags + ['-c', wrapper, '-o', objects / (shard.stem + '.o')])
            print('Checking cached native objects and their dependencies...', flush=True)
            compiler_identity = tree_digest(kit / 'compiler')
            cache = ObjectCache(root / '.launcher/native-objects/v1')
            counts = {'reused': 0, 'compiled': 0}
            with ThreadPoolExecutor(max_workers=jobs) as workers:
                futures = [workers.submit(compile_unit, command, run, cache, compiler_identity,
                                          source, generated, objects) for command in commands]
                for index, future in enumerate(as_completed(futures), 1):
                    counts[future.result()] += 1
                    print(f'Prepared {index}/{len(commands)} units: {counts["reused"]} reused, {counts["compiled"]} compiled', flush=True)
            pending = destination / 'takedown-recomp.pending.exe'
            link_inputs = [kit / 'objects/main.cpp.obj', kit / 'objects/run_diagnostics.cpp.obj', kit / 'objects/takedown-version.rc.obj',
                           *sorted(command[-1] for command in commands), kit / 'objects/libtakedown_core.a']
            link_flags = ['-O3', '-DNDEBUG', '-flto=' + str(jobs), '-Wl,--stack,67108864',
                          '-lSDL3', '-lzstd', '-lavcodec', '-lavutil', '-lws2_32', '-lwinhttp',
                          '-lkernel32', '-luser32', '-lgdi32', '-lwinspool', '-lshell32', '-lole32',
                          '-loleaut32', '-luuid', '-lcomdlg32', '-ladvapi32', '-lcrypt32']
            linked_cache = ObjectCache(root / '.launcher/native-linked/v1')
            key = link_key(link_flags, compiler_identity, link_inputs)
            if linked_cache.restore(key, pending):
                print('Reused the verified optimized link (all link inputs unchanged).', flush=True)
            else:
                print('Linking the updated game; reusing cached optimizations where possible...', flush=True)
                link_incrementally([gxx, sysroot, *link_flags[:4], *link_inputs,
                                    '-L' + str(kit / 'compiler/lib'), *link_flags[4:], '-o', pending],
                                   run, root, compiler_identity)
                linked_cache.store(key, pending)
            pending.replace(executable)
            temporary = receipt.with_suffix('.tmp')
            temporary.write_text(json.dumps({'build_id': manifest['build_id'], 'executable_sha256': digest(executable)}))
            temporary.replace(receipt)
            print('Optimized game setup complete.', flush=True)
            return executable
        finally:
            lock.seek(0)
            msvcrt.locking(lock.fileno(), msvcrt.LK_UNLCK, 1)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--release', type=Path, required=True)
    parser.add_argument('--install-root', type=Path, required=True)
    parser.add_argument('--jobs', type=int, default=max(1, min(8, (os.cpu_count() or 2) // 2)))
    options = parser.parse_args()
    if not 1 <= options.jobs <= 8:
        parser.error('jobs must be between 1 and 8')
    setup(options.release, options.install_root, options.jobs)
