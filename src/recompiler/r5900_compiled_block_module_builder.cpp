R5900CompiledBlockModuleBuildResult build_r5900_compiled_block_module(
    const std::span<const R5900WordExtractionResult> extractions,
    const std::size_t maximum_generated_blocks, const bool enable_load_fusion) {
    const std::vector<ValidatedRange> ranges = validate_and_canonicalize_extractions(extractions);
    R5900CompiledBlockModuleBuildResult result;
    std::vector<AcceptedBlock> accepted_blocks;
    for (const ValidatedRange& range : ranges) {
        const R5900WordExtractionResult& extraction = *range.extraction;
        for (std::size_t index = 0U; index < extraction.words.size(); ++index) {
            const guest::GuestAddress pc =
                extraction.start_address + static_cast<guest::GuestAddress>(index * 4U);
            const std::uint32_t word = extraction.words[index];
            const guest::DecodedR5900Instruction decoded = guest::decode_r5900(pc, word);
            const R5900CompiledBlockLiftResult lifted =
                lift_r5900_instruction_to_compiled_block_cpp(pc, word);
            R5900CompiledBlockModuleInventoryEntry entry{
                .address = pc,
                .retail_word = word,
                .disposition = R5900CompiledBlockModuleDisposition::LifterRejected,
            };
            if (lifted.diagnostic.has_value()) {
                entry.lifter_diagnostic = lifted.diagnostic->code;
                entry.detail = lifted.diagnostic->message;
                result.inventory.push_back(entry);
                continue;
            }
            if (accepted_blocks.size() >= maximum_generated_blocks) {
                entry.disposition = R5900CompiledBlockModuleDisposition::GenerationLimitExceeded;
                entry.detail = "generated-block limit was reached before this supported instruction";
                result.inventory.push_back(entry);
                continue;
            }
            entry.disposition = R5900CompiledBlockModuleDisposition::Accepted;
            entry.generated_name = lifted.generated_name;
            entry.detail = "instruction lifted into one resumable compiled block";
            result.inventory.push_back(entry);
            bool straight_line_fusible = false;
            switch (decoded.kind) {
            case guest::R5900InstructionKind::Nop:
            case guest::R5900InstructionKind::Sll:
            case guest::R5900InstructionKind::Srl:
            case guest::R5900InstructionKind::Sra:
            case guest::R5900InstructionKind::Dsll:
            case guest::R5900InstructionKind::Mthi:
            case guest::R5900InstructionKind::Mtlo:
            case guest::R5900InstructionKind::Mult:
            case guest::R5900InstructionKind::Addu:
            case guest::R5900InstructionKind::Daddu:
            case guest::R5900InstructionKind::Subu:
            case guest::R5900InstructionKind::And:
            case guest::R5900InstructionKind::Or:
            case guest::R5900InstructionKind::Slt:
            case guest::R5900InstructionKind::Sltu:
            case guest::R5900InstructionKind::Slti:
            case guest::R5900InstructionKind::Sltiu:
            case guest::R5900InstructionKind::Mtsah:
            case guest::R5900InstructionKind::Addiu:
            case guest::R5900InstructionKind::Andi:
            case guest::R5900InstructionKind::Ori:
            case guest::R5900InstructionKind::Xori:
            case guest::R5900InstructionKind::Lui:
            case guest::R5900InstructionKind::Mfc1:
            case guest::R5900InstructionKind::Mtc1:
            case guest::R5900InstructionKind::AddS:
            case guest::R5900InstructionKind::SubS:
            case guest::R5900InstructionKind::MulS:
            case guest::R5900InstructionKind::DivS:
            case guest::R5900InstructionKind::SqrtS:
            case guest::R5900InstructionKind::AbsS:
            case guest::R5900InstructionKind::NegS:
            case guest::R5900InstructionKind::MovS:
            case guest::R5900InstructionKind::CvtSW:
            case guest::R5900InstructionKind::AddaS:
            case guest::R5900InstructionKind::SubaS:
            case guest::R5900InstructionKind::MulaS:
            case guest::R5900InstructionKind::MaddS:
            case guest::R5900InstructionKind::MsubS:
            case guest::R5900InstructionKind::MaddaS:
            case guest::R5900InstructionKind::MsubaS:
            case guest::R5900InstructionKind::Qmtc2:
            case guest::R5900InstructionKind::VaddX:
            case guest::R5900InstructionKind::VsubW:
            case guest::R5900InstructionKind::VminiW:
            case guest::R5900InstructionKind::VMulX:
            case guest::R5900InstructionKind::Mthi1:
            case guest::R5900InstructionKind::Mtlo1:
            case guest::R5900InstructionKind::Padduw:
            case guest::R5900InstructionKind::Paddub:
            case guest::R5900InstructionKind::Pcpyh:
            case guest::R5900InstructionKind::Pcpyld:
                straight_line_fusible = true;
                break;
            default:
                break;
            }
            bool guarded_load = false;
            if (enable_load_fusion) {
                std::uint32_t guard_width = 0U;
                switch (decoded.kind) {
                case guest::R5900InstructionKind::Lb:
                case guest::R5900InstructionKind::Lbu:
                    guard_width = 1U;
                    break;
                case guest::R5900InstructionKind::Lh:
                case guest::R5900InstructionKind::Lhu:
                    guard_width = 2U;
                    break;
                case guest::R5900InstructionKind::Lwc1:
                case guest::R5900InstructionKind::Lw:
                    guard_width = 4U;
                    break;
                case guest::R5900InstructionKind::Ld:
                    guard_width = 8U;
                    break;
                case guest::R5900InstructionKind::Lq:
                case guest::R5900InstructionKind::Lqc2:
                    guard_width = 16U;
                    break;
                    guard_width = 0U;
                    break;
                default:
                    break;
                }
                guarded_load = guard_width != 0U;
            }
            AcceptedBlock accepted{};
            accepted.address = pc;
            accepted.retail_word = word;
            accepted.generated_name = lifted.generated_name;
            accepted.implementation_source = lifted.cpp_source;
            accepted.instruction = decoded;
            accepted.straight_line_fusible = straight_line_fusible;
            accepted.guarded_load = guarded_load;
            accepted_blocks.push_back(std::move(accepted));
        }
    }
    for (std::size_t begin = 0U; begin < accepted_blocks.size();) {
        std::size_t end = begin + 1U;
        while (end < accepted_blocks.size() && accepted_blocks[end].straight_line_fusible) {
            ++end;
        }
        const std::size_t run_length = end - begin;
        std::string span_name;
        if (run_length > 1U) {
            span_name = "recomp_span_" + bare_hex32(accepted_blocks[begin].address) + "_" +
                        bare_hex32(accepted_blocks[end - 1U].address + 4U);
        }
        for (std::size_t position = begin; position < end; ++position) {
            accepted_blocks[position].span_name = span_name;
            accepted_blocks[position].span_maximum_instructions = run_length;
        }
        begin = end;
    }
    result.cpp_source = compose_module_source(ranges, accepted_blocks);
    return result;
}

