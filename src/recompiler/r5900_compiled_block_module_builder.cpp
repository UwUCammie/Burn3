[[nodiscard]] std::string hex32(const std::uint32_t value) {
    std::ostringstream output;
    output << "0x" << std::hex << std::nouppercase << std::setfill('0') << std::setw(8) << value;
    return output.str();
}

[[nodiscard]] std::string bare_hex32(const std::uint32_t value) {
    return hex32(value).substr(2U);
}

struct ValidatedRange {
    const R5900WordExtractionResult* extraction{nullptr};
    std::uint64_t end_address{0U};
};

struct AcceptedBlock {
    guest::GuestAddress address{};
    std::uint32_t retail_word{};
    std::string generated_name{};
    std::string implementation_source{};
    std::uint32_t span_position{};
    guest::DecodedR5900Instruction instruction{};
    bool straight_line_fusible{false};
    bool guarded_load{false};
    std::string span_name{};
    std::size_t span_maximum_instructions{};
};

std::string compose_module_source(const std::vector<ValidatedRange>& ranges,
                                  const std::vector<AcceptedBlock>& accepted_blocks) {
    std::ostringstream output;
    output << "// Generated by build_r5900_compiled_block_module; do not edit by hand.\n";
    output << "#include \"takedown/guest/ee_memory.hpp\"\n";
    output << "#include \"takedown/guest/r5900_state.hpp\"\n";
    output << "#include \"takedown/guest/vu0_macro_fmac.hpp\"\n";
    output << "#include \"takedown/runtime/compiled_block_dispatcher.hpp\"\n\n";
    output << "#include <array>\n";
    output << "#include <bit>\n";
    output << "#include <cmath>\n";
    output << "#include <cstddef>\n";
    output << "#include <cstdint>\n";
    output << "#include <stdexcept>\n";
    output << "#include <string>\n\n";
    output << "#ifndef TAKEDOWN_R5900_BLOCK_MODULE_REGISTRATION_SYMBOL\n";
    output << "#define TAKEDOWN_R5900_BLOCK_MODULE_REGISTRATION_SYMBOL register_generated_r5900_block_module\n";
    output << "#endif\n";
    output << "#ifndef TAKEDOWN_R5900_BLOCK_MODULE_PREFLIGHT_SYMBOL\n";
    output << "#define TAKEDOWN_R5900_BLOCK_MODULE_PREFLIGHT_SYMBOL preflight_generated_r5900_block_module\n";
    output << "#endif\n\n";
    for (const AcceptedBlock& block : accepted_blocks) {
        output << block.implementation_source << '\n';
    }
    output << "namespace takedown::recompiler::generated {\n\n";
    output << "namespace {\n\n";
    for (const ValidatedRange& range : ranges) {
        const std::string suffix = bare_hex32(range.extraction->start_address);
        output << "constexpr takedown::guest::GuestAddress kFullRangeStart_" << suffix << " = "
               << hex32(range.extraction->start_address) << "U;\n";
        const std::vector<std::uint32_t>& words = range.extraction->words;
        output << "constexpr std::array<std::uint32_t, " << words.size() << "U> kFullRangeSignature_"
               << suffix << "{\n";
        for (const std::uint32_t word : words) {
            output << "    " << hex32(word) << "U,\n";
        }
        output << "};\n\n";
    }
    output << "template <std::size_t Size>\n";
    output << "bool has_exact_full_range_signature(\n";
    output << "    const takedown::guest::EeMemory& memory,\n";
    output << "    const takedown::guest::GuestAddress start,\n";
    output << "    const std::array<std::uint32_t, Size>& signature) {\n";
    output << "    if (!memory.contains(start, signature.size() * sizeof(std::uint32_t))) {\n";
    output << "        return false;\n";
    output << "    }\n";
    output << "    for (std::size_t index = 0U; index < signature.size(); ++index) {\n";
    output << "        const auto pc = start +\n";
    output << "            static_cast<takedown::guest::GuestAddress>(index * 4U);\n";
    output << "        if (memory.read_u32_le(pc) != signature[index]) {\n";
    output << "            return false;\n";
    output << "        }\n";
    output << "    }\n";
    output << "    return true;\n";
    output << "}\n\n";
    output << "void require_registration_or_reviewed_override(\n";
    output << "    const takedown::runtime::CompiledBlockRegistrationResult& result,\n";
    output << "    const char* name) {\n";
    output << "    if (result.registered() ||\n";
    output << "        result.status == takedown::runtime::\n";
    output << "            CompiledBlockRegistrationStatus::DuplicateAddress) {\n";
    output << "        return;\n";
    output << "    }\n";
    output << "    throw std::logic_error(\n";
    output << "        std::string{\"could not register generated R5900 block: \"} + name);\n";
    output << "}\n\n";
    output << "} // namespace\n\n";
    struct SpanRun {
        std::size_t begin;
        std::size_t end;
    };
    std::vector<SpanRun> runs;
    for (std::size_t index = 0; index < accepted_blocks.size(); ++index) {
        if (accepted_blocks[index].implementation_source.empty()) {
            continue;
        }
        if (index != 0 && accepted_blocks[index - 1].span_name == accepted_blocks[index].span_name) {
            continue;
        }
        std::size_t end = index + 1;
        while (end < accepted_blocks.size() &&
               accepted_blocks[end].span_name == accepted_blocks[index].span_name) {
            ++end;
        }
        runs.push_back(SpanRun{.begin = index, .end = end});
    }
    for (const SpanRun& run : runs) {
        output << "takedown::runtime::CompiledBlockSpanExecutionResult\n"
               << accepted_blocks.at(run.begin).span_name << "(\n";
        output << "    takedown::guest::R5900State& cpu,\n";
        output << "    takedown::guest::EeMemory& memory,\n";
        output << "    const takedown::runtime::CompiledBlockBudget& budget,\n";
        output << "    const takedown::runtime::CompiledBlockExecutionServices& services) {\n";
        output << "    if (budget.maximum_retired_instructions < 2U ||\n";
        output << "        budget.maximum_ee_cycles < 2U) {\n";
        output << "        return {.execution = {\n";
        output << "                    .exit = takedown::runtime::CompiledBlockExit::BudgetExhausted,\n";
        output << "                },\n";
        output << "                .stop_reason =\n";
        output << "                    takedown::runtime::CompiledBlockSpanStopReason::ExecutionBoundary};\n";
        output << "    }\n";
        output << "    std::size_t index;\n";
        output << "    switch (cpu.pc()) {\n";
        for (std::size_t position = run.begin; position < run.end; ++position) {
            output << "    case " << hex32(accepted_blocks[position].address) << "U:\n";
            output << "        index = " << position - run.begin << "U;\n";
            output << "        break;\n";
        }
        output << "    default:\n";
        output << "        throw std::logic_error(\n";
        output << "            \"generated span entered outside its registered instruction run\");\n";
        output << "    }\n";
        output << "    const auto completed_prefix =\n";
        output << "        [](const std::uint32_t retired,\n";
        output << "           const takedown::runtime::CompiledBlockSpanStopReason reason) {\n";
        output << "            return takedown::runtime::CompiledBlockSpanExecutionResult{\n";
        output << "                .execution = {\n";
        output << "                    .exit = takedown::runtime::CompiledBlockExit::Safepoint,\n";
        output << "                    .retired_instructions = retired,\n";
        output << "                    .ee_cycles = retired,\n";
        output << "                },\n";
        output << "                .stop_reason = reason,\n";
        output << "            };\n";
        output << "        };\n";
        output << "    std::uint32_t retired = 0U;\n";
        output << "    while (true) {\n";
        output << "        const auto instruction_address = " << hex32(accepted_blocks[run.begin].address)
               << "U +\n";
        output << "            static_cast<takedown::guest::GuestAddress>(index) * 4U;\n";
        output << "        switch (index) {\n";
        for (std::size_t position = run.begin; position < run.end; ++position) {
            const AcceptedBlock& block = accepted_blocks[position];
            output << "        case " << position - run.begin << "U: {\n";
            output << "            // " << hex32(block.address) << ": "
                   << format_r5900_instruction(block.instruction) << " (word " << hex32(block.retail_word)
                   << ")\n";
            output << "            break;\n";
            output << "        }\n";
        }
        output << "        default:\n";
        output << "            throw std::logic_error(\n";
        output << "                \"generated span instruction index left its registered run\");\n";
        output << "        }\n";
        output << "        ++retired;\n";
        output << "        if (cpu.pc() != instruction_address + 4U) {\n";
        output << "            throw std::logic_error(\n";
        output << "                \"generated span instruction did not advance sequentially\");\n";
        output << "        }\n";
        output << "        if (services.progress_checkpoint &&\n";
        output << "            !services.progress_checkpoint.callback(\n";
        output << "                services.progress_checkpoint.context, retired, retired)) {\n";
        output << "            return {completed_prefix(\n";
        output << "                retired,\n";
        output << "                takedown::runtime::CompiledBlockSpanStopReason::ProgressCheckpoint)};\n";
        output << "        }\n";
        output << "        if (retired >= budget.maximum_retired_instructions ||\n";
        output << "            retired >= budget.maximum_ee_cycles) {\n";
        output << "            return {completed_prefix(\n";
        output << "                retired, takedown::runtime::CompiledBlockSpanStopReason::FusedBudget)};\n";
        output << "        }\n";
        output << "        if (cpu.is_executing_delay_slot()) {\n";
        output << "            return {completed_prefix(\n";
        output << "                retired, takedown::runtime::CompiledBlockSpanStopReason::PostInstructionDelaySlot)};\n";
        output << "        }\n";
        output << "        if (services.scalar_barrier != nullptr &&\n";
        output << "            services.scalar_barrier(cpu.pc())) {\n";
        output << "            return {completed_prefix(\n";
        output << "                retired, takedown::runtime::CompiledBlockSpanStopReason::ScalarBarrier)};\n";
        output << "        }\n";
        output << "        ++index;\n";
        output << "        if (index == " << run.end - run.begin << "U) {\n";
        output << "            return {completed_prefix(\n";
        output << "                retired, takedown::runtime::CompiledBlockSpanStopReason::MissingSuccessor)};\n";
        output << "        }\n";
        output << "        std::uint32_t expected_successor_word = 0U;\n";
        output << "        switch (index) {\n";
        for (std::size_t position = run.begin + 1; position < run.end; ++position) {
            output << "        case " << position - run.begin << "U:\n";
            output << "            expected_successor_word = " << hex32(accepted_blocks[position].retail_word)
                   << "U;\n";
            output << "            break;\n";
        }
        output << "        default:\n";
        output << "            throw std::logic_error(\n";
        output << "                \"generated span successor index left its registered run\");\n";
        output << "        }\n";
        output << "        if (!memory.contains(cpu.pc(), sizeof(std::uint32_t)) ||\n";
        output << "            memory.read_u32_le(cpu.pc()) != expected_successor_word) {\n";
        output << "            return {completed_prefix(\n";
        output << "                retired, takedown::runtime::CompiledBlockSpanStopReason::SuccessorLiveWordMismatch)};\n";
        output << "        }\n";
        output << "    }\n";
        output << "}\n\n";
    }
    output << "bool TAKEDOWN_R5900_BLOCK_MODULE_PREFLIGHT_SYMBOL(\n";
    output << "    const takedown::guest::EeMemory& memory) {\n";
    output << "    if (";
    for (std::size_t index = 0U; index < ranges.size(); ++index) {
        const std::string suffix = bare_hex32(ranges[index].extraction->start_address);
        output << "\n        !has_exact_full_range_signature(\n";
        output << "            memory, kFullRangeStart_" << suffix << ", kFullRangeSignature_" << suffix
               << ")";
        if (index + 1U != ranges.size()) {
            output << " ||";
        }
    }
    output << ") {\n";
    output << "        return false;\n";
    output << "    }\n";
    output << "    return true;\n";
    output << "}\n\n";
    output << "bool TAKEDOWN_R5900_BLOCK_MODULE_REGISTRATION_SYMBOL(\n";
    output << "    takedown::runtime::CompiledBlockDispatcher& dispatcher,\n";
    output << "    const takedown::guest::EeMemory& memory) {\n";
    output << "    // Verify every supplied retail range before the first table mutation.\n";
    output << "    if (!TAKEDOWN_R5900_BLOCK_MODULE_PREFLIGHT_SYMBOL(memory)) {\n";
    output << "        return false;\n";
    output << "    }\n\n";
    for (const AcceptedBlock& block : accepted_blocks) {
        // RECOVERY: the GIMPLE emits the generated name twice in this register_block argument list.
        output << "    require_registration_or_reviewed_override(\n";
        output << "        dispatcher.register_block(\n";
        output << "            " << hex32(block.address) << "U, \"" << block.generated_name << "\", "
               << block.generated_name << ", " << hex32(block.retail_word) << "U, ";
        output << "takedown::runtime::CompiledBlockTraits{";
        output << ".straight_line_fusible = " << (block.straight_line_fusible ? "true" : "false");
        if (block.guarded_load) {
            unsigned int width = 0U;
            switch (block.instruction.kind) {
            case guest::R5900InstructionKind::Lb:
            case guest::R5900InstructionKind::Lbu:
                width = 1U;
                break;
            case guest::R5900InstructionKind::Lh:
            case guest::R5900InstructionKind::Lhu:
                width = 2U;
                break;
            case guest::R5900InstructionKind::Lw:
            case guest::R5900InstructionKind::Lwc1:
                width = 4U;
                break;
            case guest::R5900InstructionKind::Ld:
                width = 8U;
                break;
            case guest::R5900InstructionKind::Lq:
            case guest::R5900InstructionKind::Lqc2:
                width = 16U;
                break;
            default:
                width = 0U;
                break;
            }
            output << ", .load_fusion_guard = +[](const takedown::guest::R5900State& cpu, ";
            output << "const takedown::guest::EeMemory& load_memory) noexcept {\n";
            output << "                const std::uint32_t address = (cpu.read_gpr_u32("
                   << static_cast<unsigned int>(block.instruction.rs) << "U) + "
                   << hex32(static_cast<std::uint32_t>(block.instruction.signed_immediate())) << "U)";
            if (block.instruction.kind == guest::R5900InstructionKind::Lq) {
                output << " & ~0x0fU";
            }
            output << ";\n                return (address & " << width - 1U
                   << "U) == 0U && load_memory.is_main_ram_range(address, " << width << "U);\n";
            output << "            }";
        }
        output << "}";
        if (block.span_maximum_instructions != 0U) {
            output << ",\n";
            output << "            takedown::runtime::CompiledBlockSpan{" << block.span_name << ", "
                   << block.span_maximum_instructions << "U}";
        }
        output << "),\n";
        output << "        \"" << block.generated_name << "\");\n";
    }
    output << "    return true;\n";
    output << "}\n\n";
    output << "} // namespace takedown::recompiler::generated\n";
    return output.str();
}


std::vector<ValidatedRange> validate_and_canonicalize_extractions(
    const std::span<const R5900WordExtractionResult> extractions) {
    if (extractions.empty()) {
        throw std::invalid_argument(
            "compiled-block module requires at least one extracted word range");
    }
    std::vector<ValidatedRange> ranges;
    ranges.reserve(extractions.size());
    for (const R5900WordExtractionResult& extraction : extractions) {
        if (extraction.words.empty()) {
            throw std::invalid_argument(
                "compiled-block module requires a successful nonempty word extraction");
        }
        if (!extraction.elf_executable_range_validated) {
            throw std::invalid_argument(
                "compiled-block module requires ELF-executable-validated extraction provenance");
        }
        if ((extraction.start_address & 3U) != 0U) {
            throw std::invalid_argument(
                "compiled-block module extraction start address is not instruction aligned");
        }
        const std::uint64_t end_address =
            static_cast<std::uint64_t>(extraction.start_address) + 4U * extraction.words.size();
        if (end_address > 0x100000000ULL) {
            throw std::invalid_argument(
                "compiled-block module extraction range overflows the guest address space");
        }
        ranges.push_back(ValidatedRange{.extraction = &extraction, .end_address = end_address});
    }
    std::sort(ranges.begin(), ranges.end(),
              [](const auto& left, const auto& right) {
                  return left.extraction->start_address < right.extraction->start_address;
              });
    for (std::size_t index = 1U; index < ranges.size(); ++index) {
        if (ranges[index].extraction->start_address < ranges[index - 1U].end_address) {
            throw std::invalid_argument(
                "compiled-block module extracted word ranges overlap or duplicate an address");
        }
    }
    return ranges;
}


